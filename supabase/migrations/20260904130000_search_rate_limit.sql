-- Rate-limit table for search edge function.
-- Stores per-IP search request timestamps for rolling-window throttling.
-- Migration is idempotent: CREATE TABLE IF NOT EXISTS; rows are purged
-- automatically by the edge function on each invocation.

CREATE TABLE IF NOT EXISTS public.search_rate_limit (
  id bigint generated by default as identity primary key,
  ip text not null,
  created_at timestamptz not null default now()
);

-- GIN index for fast per-IP rolling-window counts.
CREATE INDEX IF NOT EXISTS idx_search_rate_limit_ip ON public.search_rate_limit (ip, created_at);

-- Comment so future DBAs know the purpose.
COMMENT ON TABLE public.search_rate_limit IS 'Rate-limiting store for /search edge function: per-IP rolling-window search request count.';