-- Indivisible Fair Oaks-Carmichael — Schema Reference
-- =============================================================================
--
-- The canonical schema lives in:
--   supabase/migrations/00000000000000_init.sql
--
-- That file is the single source of truth. Run it to provision a fresh
-- database or to verify the expected state of an existing one. It is
-- fully idempotent (CREATE IF NOT EXISTS / DROP IF EXISTS / ON CONFLICT DO NOTHING).
--
-- To apply to a fresh database:
--   psql $DATABASE_URL -f supabase/migrations/00000000000000_init.sql
--
-- To push via Supabase CLI:
--   supabase db push
--
