#!/usr/bin/env bun
/**
 * No-Node-runtime guard.
 *
 * ## What it protects
 *
 * This repository runs on Bun. There is no `node` binary on the runner hosts,
 * no `setup-node` step in any workflow, and `package.json` declares
 * `engines.bun` and nothing else. The migration was done once; this guard is
 * what keeps it done.
 *
 * A migration that is only a migration is a migration that a single
 * convenient `#!/usr/bin/env node` can undo, and nothing in CI would notice
 * until a job failed on a machine that had no Node — which is every machine
 * this project actually runs on. The failure is real, but it is late, remote
 * and intermittent-looking.
 *
 * ## What it blocks, and why each one matters
 *
 *   - `#!/usr/bin/env node` shebangs — the file becomes unrunnable here. The
 *     shebang is also the only thing that decides which interpreter a script
 *     gets, so it is the whole of the risk.
 *   - `node:child_process` — the only builtin that *starts another runtime*.
 *     `node:fs`, `node:path` and `node:crypto` are portable APIs Bun
 *     implements natively and are not Node.js in any meaningful sense; this
 *     guard deliberately does not touch them.
 *   - `npm` / `npx` / `yarn` / `pnpm` invocations — a second package manager
 *     alongside Bun produces a second lockfile, a second resolution, and a
 *     `bun install --frozen-lockfile` CI failure that looks like a supply
 *     chain attack.
 *   - `setup-node` in a workflow — the same, in CI, where it is invisible
 *     until the runner is replaced.
 *   - `engines.node` in package.json — declaring a Node engine tells a
 *     platform (Vercel, a CI image, a contributor's toolchain) that Node is a
 *     supported runtime for this project. It is not.
 *   - `node-fetch` — a Node-only shim for a runtime whose `fetch` is built in.
 *     It was also never a declared dependency here, so importing it broke on
 *     a clean install.
 *   - `dotenv` — the same failure mode, and the same cause: a package the
 *     lockfile does not promise, imported as though it did. Bun loads `.env`
 *     and `.env.local` natively.
 *
 * ## What it deliberately does not block
 *
 * `node:fs`, `node:path`, `node:crypto`, `node:os`, `node:url` and
 * `node:http` are all implemented natively by Bun. Using them is not using
 * Node.js — no Node binary is involved — and blocking them would trade a real
 * guarantee for a cosmetic one. Where Bun has a better API for the job
 * (`Bun.file`, `Bun.write`, `Bun.Glob`, `Bun.YAML`, `Bun.spawn`), the
 * project uses it, but the guard does not pretend the `node:` prefix is a
 * runtime dependency.
 *
 * ## Two modes, and why the second one exists
 *
 * The pre-commit hook passes `{staged_files}`: the files about to be
 * committed. That catches a *reintroduction* — someone adds a Node shebang and
 * the commit is refused.
 *
 * It cannot catch a violation that arrived another way: a file that was
 * committed before this guard existed, a merge that brought one in, a file
 * regenerated by a tool. Those sit there indefinitely, and the guard keeps
 * reporting a clean tree because it is only ever shown the staged subset.
 * That is the failure this project has already been bitten by — a
 * `#!/usr/bin/env node` shebang works perfectly on a laptop that still has
 * Node installed, and breaks on every machine this project actually runs on.
 *
 * So `--all` walks the whole tree. It is what CI runs, and it is the half
 * that says something about the *current* state of the repository rather than
 * about the next commit.
 *
 * ## What is excluded, and why
 *
 *   - `.agents/skills/` and `agent/skills/` — vendored, pinned in
 *     `skills-lock.json` and rewritten by `bunx skills update`. A shebang in
 *     a third-party skill is the skill author's choice, not this repository's
 *     runtime, and editing it here would be undone by the next update.
 *   - `.kiro/` and `scratch/` — local working directories, gitignored.
 *   - `node_modules/`, `.next/`, `.vercel/`, `coverage/` and friends — build
 *     output and dependencies, not source.
 *
 * ## Comments
 *
 * A rule that fires on prose teaches people to reach for the bypass, so a
 * line that is a comment is not a violation: `# It used to be installed with
 * \`npm install -g vercel@latest\`` is a sentence about the past, not a
 * command. A shebang is the exception — it is the one comment-shaped line
 * that *is* executable metadata.
 *
 * ## Two rules that are not about a line of code
 *
 * A Node.js runtime can arrive without the word "node" in the diff in any
 * obvious way. Two rules cover that, because a line-level pattern cannot:
 *
 *   - **`proxy.ts`** — Next.js 16 renamed the `middleware` file convention to
 *     `proxy`, and the rename moves the code onto Node. `middleware.ts`
 *     compiles to the Edge runtime (`server/edge/chunks/…`); `proxy.ts`
 *     compiles to a Node bundle (`server/middleware.js`). Next.js's own
 *     version history says it — *"Proxy defaults to the Node.js runtime"* —
 *     and the build rejects `export const runtime` inside a proxy file with
 *     *"Proxy always runs on Node.js runtime."* Measured on this repository,
 *     both ways. The deprecated convention is the one that keeps the auth
 *     gate off Node, so the rename is not housekeeping.
 *
 *   - **`export const runtime = 'nodejs'`** — the explicit form of the same
 *     thing. Next.js accepts only `'edge'` and `'nodejs'`, and unlike a build
 *     error, a runtime that differs between environments fails at the first
 *     request rather than at the build.
 *
 * See AGENTS.md, "Three runtimes, none of them Node".
 */

// `node:fs` and `node:path` are portable APIs Bun implements natively, and
// this guard deliberately does not block them — it blocks `node:child_process`,
// the one builtin that starts another runtime.
import { existsSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const argv = process.argv.slice(2);
const scanAll = argv.includes('--all');
const files = argv.filter((a) => !a.startsWith('--'));
const violations = [];

/**
 * Directories that are not this repository's source. Applied in both modes:
 * a vendored skill or a gitignored scratch directory is nobody's runtime.
 */
const EXCLUDED_DIRS = new Set([
  'node_modules',
  '.git',
  '.next',
  '.vercel',
  'coverage',
  'playwright-report',
  'test-results',
  '.turbo',
  'dist',
  // Vendored skills — pinned in skills-lock.json, rewritten by `bunx skills update`.
  'skills',
  // Local working directories, gitignored.
  '.kiro',
  'scratch',
]);

/**
 * The file types the guard reads. The pre-commit glob has always been these
 * extensions, and the tree walk uses the same set so the two modes cannot
 * disagree about what is in scope.
 *
 * Markdown is not among them, and that is deliberate rather than an
 * oversight: prose mentioning `npm install -g vercel` is a sentence about the
 * past, not a command. The files that decide the runtime are the ones that
 * execute.
 */
const SCANNED_EXTENSIONS = new Set([
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.ts',
  '.tsx',
  '.json',
  '.yml',
  '.yaml',
  '.toml',
  '.sh',
]);

/**
 * Whether a path is one this guard has no business judging.
 */
function isExcluded(path) {
  const parts = path.split('/').filter(Boolean);
  if (parts.some((p) => EXCLUDED_DIRS.has(p))) return true;
  const dot = path.lastIndexOf('.');
  if (dot === -1) return true;
  return !SCANNED_EXTENSIONS.has(path.slice(dot));
}

/**
 * A line that is a comment rather than code. A shebang is deliberately not a
 * comment here: it is executable metadata, and it is the one line whose
 * comment shape does not mean "inert".
 */
function isComment(line) {
  if (/^#!/.test(line)) return false;
  return /^\s*#/.test(line) || /^\s*\/\//.test(line) || /^\s*\*/.test(line);
}

/**
 * Each rule is a pattern with the reason it exists. A finding quotes the
 * reason, because a guard that says only "no" teaches people to reach for
 * the bypass.
 */
const RULES = [
  {
    name: 'node shebang',
    why: 'a `node` shebang makes the file unrunnable — there is no Node runtime here',
    test: (line) => /^#!\s*\/usr\/bin\/env\s+node\b/.test(line) || /^#!\s*\/usr\/bin\/node\b/.test(line),
    // The shebang is the executable form of a comment-shaped line.
    comments: false,
  },
  {
    name: 'node:child_process',
    why: 'the only builtin that starts another runtime — use Bun.spawn / Bun.spawnSync (scripts/bun-exec.mjs)',
    test: (line) => /from\s+['"]node:child_process['"]/.test(line) || /require\(['"]node:child_process['"]\)/.test(line),
  },
  {
    name: 'second package manager',
    why: 'npm/npx/yarn/pnpm alongside Bun means a second lockfile and a second resolution',
    // The prefix class includes quotes and backticks because the common case
    // is a package manager named inside a command string — `execSync('npm
    // install')` — not only at the start of a line.
    //
    // `npm` is matched against its subcommands, because the bare word appears
    // in prose and in unrelated identifiers. `npx`, `yarn` and `pnpm` are
    // matched against any subcommand: for all three, the subcommand *is* the
    // thing that installs or runs a package.
    test: (line) =>
      /(^|[\s;&|('"`=])npm\s+(install|ci|add|exec|run|publish|uninstall)\b/.test(line) ||
      /(^|[\s;&|('"`=])(npx|yarn|pnpm)\s+\S/.test(line),
  },
  {
    name: 'setup-node action',
    why: 'the CI form of the same mistake — Bun is installed by oven-sh/setup-bun',
    test: (line) => /uses:\s*actions\/setup-node\b/.test(line),
  },
  {
    name: 'node engine',
    why: 'declaring a Node engine tells a platform that Node is supported here — it is not',
    test: (line) => /"engines"\s*:\s*\{[^}]*"node"/.test(line),
  },
  {
    name: 'node runtime declaration',
    why:
      'a `node@<version>` runtime entry makes a tool download and run a Node.js runtime — ' +
      'the one thing this repository does not have. It is the same mistake as a Node shebang, ' +
      'in the shape a linter config takes.',
    // The version is required, so that a prose mention of "node@" — a
    // package name, a URL, a note in a comment — is not a finding. A runtime
    // declaration always carries a version.
    test: (line) => /(^|[\s'"\[,])node@\d+\.\d+/.test(line),
  },
  {
    name: 'node-fetch',
    why: 'Bun has a built-in fetch, and node-fetch was never a declared dependency here',
    test: (line) => /from\s+['"]node-fetch['"]/.test(line),
  },
  {
    name: 'dotenv',
    why: 'Bun loads .env and .env.local natively, and dotenv is not a declared dependency here',
    test: (line) => /from\s+['"]dotenv['"]/.test(line),
  },
  {
    name: 'nodejs runtime export',
    why:
      "pinning the routing middleware to Node.js is a Node.js runtime by another name — " +
      "Next.js accepts only 'edge' and 'nodejs', and unlike a build error, a runtime that " +
      "differs between environments fails at the first request rather than at the build",
    test: (line) => /export\s+const\s+runtime\s*(?::[^=]+)?=\s*['"]nodejs['"]/.test(line),
  },
];

/**
 * Rules about the *file* rather than its contents.
 *
 * A Node.js runtime can be introduced without the word "node" appearing in
 * the diff in any obvious way — by changing which file convention Next.js
 * picks up. That is not a line-level pattern, so it is checked as a path.
 *
 * **`proxy.ts` is a Node.js surface.** Next.js 16 renamed the `middleware`
 * file convention to `proxy`, and the rename moves the code: `middleware.ts`
 * compiles to the Edge runtime (`server/edge/chunks/…`), while `proxy.ts`
 * compiles to a Node bundle (`server/middleware.js`). Next.js's own version
 * history says it — *"Proxy defaults to the Node.js runtime"* — and the build
 * rejects `export const runtime` inside a proxy file with *"Proxy always runs
 * on Node.js runtime."* Measured on this repository, both ways.
 *
 * So the deprecated convention is the one that keeps the auth gate off Node,
 * and the rename is not housekeeping. See AGENTS.md, "Three runtimes, none of
 * them Node".
 */
const FILE_RULES = [
  {
    name: 'next.js proxy convention',
    why:
      "Next.js 16's `proxy` file convention compiles to a Node.js bundle; `middleware.ts` compiles to the Edge runtime. " +
      'Renaming this file would reintroduce the one runtime this project does not have — see AGENTS.md, "Three runtimes, none of them Node".',
    test: (file) => /(?:^|\/)proxy\.(?:ts|js|tsx|jsx)$/.test(file),
  },
];

/**
 * Whether a directory is a repository root.
 *
 * The presence of a `.git` entry is not enough. A `.git` *directory* without a
 * `HEAD` is a half-created repository — and `~/dev/work` has exactly one,
 * which `git` itself rejects as "not a git repository". Treating it as a
 * boundary would make "the whole tree" mean that directory, and the tree walk
 * would then cover every project inside it.
 *
 * A `.git` *file* is the other shape: a worktree or submodule pointer, whose
 * target is a real repository. That one is accepted on sight.
 */
function isRepositoryRoot(dir) {
  const dotGit = join(dir, '.git');
  if (!existsSync(dotGit)) return false;
  if (statSync(dotGit).isDirectory()) return existsSync(join(dotGit, 'HEAD'));
  return true;
}

/**
 * The repository root — the directory the tree walk starts from.
 *
 * `process.cwd()` is not it. The hook can be run from a subdirectory, and a
 * tree walk from there covers the wrong tree entirely: it either reports
 * violations belonging to a *sibling* checkout, or — worse — finds none,
 * because the part of the repository that matters is above it. Both are the
 * same failure: a guard reporting success while measuring the wrong thing.
 *
 * Walking up to the `.git` boundary is what makes "the whole tree" mean the
 * same thing wherever the command was invoked from.
 *
 * `null` when there is no boundary. "The whole tree" is undefined without
 * one, and scanning whatever directory the command happened to be run from
 * would report a clean tree for a repository it never looked at — the
 * failure this function exists to prevent. The caller refuses rather than
 * guessing.
 */
function findRepoRoot(start) {
  let dir = resolve(start);
  for (;;) {
    if (isRepositoryRoot(dir)) return dir;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/**
 * Every file the guard would judge, relative to the repository root.
 */
async function collectTreeFiles(root) {
  const glob = new Bun.Glob('**/*');
  const found = [];
  for await (const rel of glob.scan({ cwd: root, dot: true })) {
    if (isExcluded(rel)) continue;
    found.push(rel);
  }
  return found;
}

const root = findRepoRoot(process.cwd());

// The tree walk needs a boundary; checking an explicit list of files does not,
// so the refusal is scoped to `--all`.
if (scanAll && root === null) {
  console.log('');
  console.log('✖  no-node-runtime: not inside a repository — "the whole tree" has no boundary.');
  console.log(`   Looked for a .git above: ${resolve(process.cwd())}`);
  console.log('   Run this from inside the repository, or pass the files to check.');
  console.log('');
  process.exit(1);
}

/** The base the tree walk and the file reads are relative to. */
const base = root ?? resolve(process.cwd());

let targets = files.filter((f) => !isExcluded(f));

if (scanAll) {
  targets = await collectTreeFiles(root);
}

/**
 * Resolve a path for reading. Staged paths arrive relative to the repository
 * root, and the tree walk produces them that way too, so the repository root
 * is the base — with the working directory as a fallback for an absolute path
 * or a path that is already resolvable from here.
 *
 * `existsSync` rather than `Bun.file(...).exists()`: the latter returns a
 * Promise, and a Promise is truthy, so the fallback branch would never be
 * reached and every path would resolve against the working directory instead
 * of the repository root. That reads as "the tree is empty" from anywhere but
 * the root, which is the failure this function exists to prevent.
 */
function resolvePath(file) {
  if (existsSync(file)) return file;
  return join(base, file);
}

let scanned = 0;

for (const file of targets) {
  const path = resolvePath(file);

  // A file-level rule fires on the path, not on a line inside it.
  for (const rule of FILE_RULES) {
    if (!rule.test(file)) continue;
    violations.push({ file, line: 0, text: file, rule });
  }

  let content;
  try {
    content = await Bun.file(path).text();
  } catch {
    continue;
  }
  scanned++;

  const lines = content.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    for (const rule of RULES) {
      if (rule.comments !== false && isComment(line)) continue;
      if (!rule.test(line)) continue;
      violations.push({
        file,
        line: i + 1,
        text: line.trim().slice(0, 120),
        rule,
      });
    }
  }
}

// A guard that scanned nothing and reported success is a control that reports
// success while measuring nothing. The tree must actually be there.
if (scanAll && scanned === 0) {
  console.log('');
  console.log('✖  no-node-runtime: scanned 0 files — the tree is not where it was expected.');
  console.log(`   Looked in: ${root}`);
  console.log('');
  process.exit(1);
}

if (violations.length > 0) {
  console.log('');
  console.log('✖  Node.js runtime reintroduced:');
  console.log('');
  for (const v of violations) {
    const where = v.line ? `${v.file}:${v.line}` : v.file;
    console.log(`  ${where}  [${v.rule.name}]`);
    console.log(`    ${v.text}`);
    console.log(`    → ${v.rule.why}`);
    console.log('');
  }
  console.log('   This project runs on Bun. See AGENTS.md → "The runtime is Bun".');
  console.log('   Bypass (emergency only): LEFTHOOK_EXCLUDE=no-node-runtime git commit');
  console.log('');
  process.exit(1);
}
